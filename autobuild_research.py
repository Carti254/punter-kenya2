"""Single-model candidate qualification for PUNTER KENYA.

Probabilities must come from the fitted Dixon-Coles score matrix. This module
checks exact SportyBet identity, market settlement and price value only.
It does not run or blend Elo, Monte Carlo, specialist or external prediction models.
"""
from __future__ import annotations

import math
import re
from collections import Counter


def _excluded(row):
    text = " ".join(str(row.get(k) or "") for k in ("market", "selection", "specifier")).casefold()
    if "btts" in text or "both teams to score" in text:
        return "excluded_btts"
    if "under 2.5" in text:
        return "excluded_under_2_5"
    if any(x in text for x in ("draw no bet", " dnb", "2up", "two up", "early payout", "two-goal lead")):
        return "unsupported_settlement"
    # No Asian/European handicaps or whole-number push lines in this version.
    if "handicap" in text or re.search(r"(?<!\d)\d+\.0+(?!\d)", text):
        return "unsupported_push_or_handicap_market"
    if any(x in text for x in ("corner", "card", "booking", "shot", "player", "first half", "half time")):
        return "unsupported_by_score_model"
    return None


def assess_candidate(row: dict, marginal_ev_floor: float = 0.0, use_dixon_coles: bool = False) -> dict | None:
    try:
        odds = float(row.get("odds"))
        probability = float(row.get("probability"))
    except (TypeError, ValueError, OverflowError):
        return None
    if not (math.isfinite(odds) and odds > 1 and math.isfinite(probability) and 0 < probability < 1):
        return None
    if str(row.get("bookmaker") or "").strip().casefold().replace(" ", "") != "sportybet":
        return None
    if not (row.get("eventId") or row.get("event_id") or row.get("sportybet_event_id")):
        return None
    if not (row.get("marketId") or row.get("market_id")):
        return None
    if not (row.get("outcomeId") or row.get("outcome_id")):
        return None
    if row.get("fixture_match_verified") is not True:
        return None
    if not str(row.get("probability_source") or "").startswith("Fitted time-decayed Dixon-Coles"):
        return None
    if row.get("model_version") != "dixon-coles-fitted-v1":
        return None
    excluded = _excluded(row)
    if excluded:
        return None
    try:
        training_n = int(row.get("training_sample") or 0)
    except (TypeError, ValueError):
        return None
    if training_n < 50:
        return None
    ev = probability * odds - 1.0
    if not math.isfinite(ev) or ev < float(marginal_ev_floor):
        return None
    item = dict(row)
    item.update({
        "odds": odds, "probability": probability,
        "implied_probability": 1.0 / odds, "fair_odds": 1.0 / probability,
        "edge": probability - 1.0 / odds, "ev": ev,
        "value_tier": "A", "research_grade": "A",
        "value_label": "Positive fitted-model expected value",
        "research_grade_reason": "Exact SportyBet event and price; probability generated by the fitted Dixon-Coles model.",
        "dixon_coles_adjusted": True,
        "research_checks": [
            "Fitted time-decayed Dixon-Coles model trained only on completed pre-kickoff results",
            "SportyBet event identity and executable price matched",
            "Model probability compared with bookmaker implied probability",
            "Expected value calculated from the same fitted score distribution",
        ],
        "research_evidence": {
            "training_sample": training_n,
            "training_teams": row.get("training_teams"),
            "rho": row.get("rho"),
            "lambda_home": row.get("lambda_home"),
            "lambda_away": row.get("lambda_away"),
            "home_recent_matches": row.get("home_recent_matches") or [],
            "away_recent_matches": row.get("away_recent_matches") or [],
        },
        "research_gaps": [],
    })
    return item


def candidate_rejection_bucket(row: dict, marginal_ev_floor: float = 0.0, use_dixon_coles: bool = False) -> str:
    try:
        odds, probability = float(row.get("odds")), float(row.get("probability"))
    except (TypeError, ValueError, OverflowError):
        return "missing_probability_or_price"
    if not (math.isfinite(odds) and odds > 1 and math.isfinite(probability) and 0 < probability < 1):
        return "invalid_probability_or_price"
    if str(row.get("bookmaker") or "").strip().casefold().replace(" ", "") != "sportybet":
        return "not_a_sportybet_price"
    if not (row.get("eventId") or row.get("event_id") or row.get("sportybet_event_id")):
        return "missing_exact_sportybet_event_id"
    if not (row.get("marketId") or row.get("market_id")):
        return "missing_exact_sportybet_market_id"
    if not (row.get("outcomeId") or row.get("outcome_id")):
        return "missing_exact_sportybet_outcome_id"
    if row.get("fixture_match_verified") is not True:
        return "unverified_fixture_identity"
    if not str(row.get("probability_source") or "").startswith("Fitted time-decayed Dixon-Coles"):
        return "not_from_fitted_dixon_coles"
    if row.get("model_version") != "dixon-coles-fitted-v1":
        return "wrong_model_version"
    excluded = _excluded(row)
    if excluded:
        return excluded
    try:
        if int(row.get("training_sample") or 0) < 50:
            return "insufficient_competition_training_history"
    except (TypeError, ValueError):
        return "missing_training_history"
    if probability * odds - 1.0 < float(marginal_ev_floor):
        return "no_positive_modelled_value"
    return "other_assessment_rejection"


def prepare_candidate_pool(rows: list[dict], marginal_ev_floor: float = 0.0, use_dixon_coles: bool = False) -> tuple[list[dict], dict]:
    pool, reasons = [], Counter()
    for row in rows or []:
        item = assess_candidate(row, marginal_ev_floor=marginal_ev_floor)
        if item is None:
            reasons[candidate_rejection_bucket(row, marginal_ev_floor)] += 1
        else:
            pool.append(item)
    pool.sort(key=lambda x: (x["ev"], x["probability"], x["odds"]), reverse=True)
    return pool, {
        "scanned": len(rows or []), "eligible": len(pool),
        "tier_a": len(pool), "tier_b": 0, "tier_c": 0,
        "research_grade_a": len(pool), "research_grade_b": 0,
        "venue_evidence_incomplete": 0, "rejected": sum(reasons.values()),
        "rejection_reasons": dict(reasons.most_common()),
        "marginal_ev_floor": marginal_ev_floor,
        "research_scope": "One fitted Dixon-Coles model, exact SportyBet price and positive estimated value.",
        "not_verified_by_this_scan": ["future lineups and injuries", "unseen team news", "pairwise accumulator dependence"],
    }


def candidate_research_summary(pool: list[dict]) -> str:
    return f"Fitted Dixon-Coles value screen: {len(pool or [])} positive-value SportyBet candidates."


def enrich_with_specialist_models(rows: list[dict], api_key: str | None = None, max_fixtures: int = 4):
    """Compatibility stub: specialist predictions are intentionally disabled."""
    return [dict(x) for x in (rows or [])], {
        "enabled": False, "fixtures_checked": 0, "matched_prices": 0,
        "reason": "Disabled: PUNTER uses one fitted Dixon-Coles prediction model.",
    }


def apply_walk_forward_calibration(rows: list[dict], validation: dict):
    """No second calibration layer: the fitted model is the sole probability source."""
    return [dict(x) for x in (rows or [])], {
        "applied": False, "reason": "Separate temperature-calibration layer removed; validate the fitted model with walk-forward tests.",
    }
